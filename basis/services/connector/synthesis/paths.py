"""Resolve upstream asset paths for provider synthesis (OpenConnector / registry / Airbyte)."""

from __future__ import annotations

import os
from pathlib import Path


def repo_root() -> Path:
    return Path(__file__).resolve().parents[4]


def batches_dir() -> Path:
    return Path(__file__).resolve().parent / "batches"


def _discover_providers_registry_yaml() -> Path | None:
    rel = Path("packages") / "providers" / "providers.yaml"
    roots = [repo_root().parent, repo_root().parent.parent]
    for root in roots:
        if not root.is_dir():
            continue
        direct = root / rel
        if direct.is_file():
            return direct
        try:
            for child in root.iterdir():
                if not child.is_dir():
                    continue
                candidate = child / rel
                if candidate.is_file():
                    return candidate
        except OSError:
            continue
    return None


def providers_registry_yaml() -> Path | None:
    raw = os.environ.get("BASIS_SYNTHESIS_PROVIDERS_REGISTRY", "").strip()
    if raw:
        path = Path(raw).expanduser()
        return path if path.is_file() else None
    return _discover_providers_registry_yaml()


def open_connector_root() -> Path | None:
    raw = os.environ.get("BASIS_SYNTHESIS_OPEN_CONNECTOR_ROOT", "").strip()
    if raw:
        path = Path(raw).expanduser()
        return path if path.is_dir() else None
    monorepo = repo_root().parent
    candidates = [
        monorepo.parent / "open-connector",
        monorepo / "open-connector",
    ]
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return None


def open_connector_catalog_dir() -> Path | None:
    """``catalog/apps`` generated by ``npm run generate:catalog`` in OpenConnector."""
    root = open_connector_root()
    if root is None:
        return None
    apps = root / "catalog" / "apps"
    return apps if apps.is_dir() else None


def legacy_anyconnect_catalog_dir() -> Path | None:
    raw = os.environ.get("BASIS_SYNTHESIS_ANYCONNECT_CATALOG", "").strip()
    if raw:
        path = Path(raw).expanduser()
        return path if path.is_dir() else None
    monorepo = repo_root().parent
    candidates = [
        monorepo / "connectors" / "catalog" / "apps",
        monorepo.parent / "basis" / "connectors" / "catalog" / "apps",
    ]
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return None


def connector_catalog_dir() -> Path | None:
    """Primary: OpenConnector ``catalog/apps``; fallback: legacy basis connectors export."""
    return open_connector_catalog_dir() or legacy_anyconnect_catalog_dir()


def anyconnect_catalog_dir() -> Path | None:
    """Alias for :func:`connector_catalog_dir` (historical name)."""
    return connector_catalog_dir()


def airbyte_connectors_root() -> Path | None:
    raw = os.environ.get("BASIS_SYNTHESIS_AIRBYTE_ROOT", "").strip()
    if raw:
        path = Path(raw).expanduser()
        return path if path.is_dir() else None
    monorepo = repo_root().parent
    candidate = (
        monorepo.parent
        / "airbyte"
        / "airbyte-integrations"
        / "connectors"
    )
    return candidate if candidate.is_dir() else None


def executor_index_path() -> Path | None:
    raw = os.environ.get("BASIS_SYNTHESIS_EXECUTOR_INDEX", "").strip()
    if raw:
        path = Path(raw).expanduser()
        return path if path.is_file() else None
    candidate = Path(__file__).resolve().parent / "executors-index.json"
    return candidate if candidate.is_file() else None
