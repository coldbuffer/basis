#!/usr/bin/env python3
"""Generate web/content/docs/{en,zh}/mcp-tools.mdx from tool_catalog MCP metadata."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_EN = REPO_ROOT / "web/content/docs/en/mcp-tools.mdx"
OUT_ZH = REPO_ROOT / "web/content/docs/zh/mcp-tools.mdx"

GENERATED_MARKER = "{/* generated by scripts/docs/generate-product-docs-mcp-tools.py; do not edit tables */}"


def _category(tool: str) -> str:
    _connector_prefixes = (
        "list_connector",
        "upsert_connector",
        "delete_connector",
        "check_connector",
        "discover_connector",
        "sync_connector",
        "invoke_connector",
        "execute_connector",
        "propose_entity_writeback",
        "describe_connector",
    )
    if any(tool.startswith(p) for p in _connector_prefixes):
        return "Connectors"
    if "ontology" in tool or "vocabulary" in tool or "alignment" in tool:
        return "Ontology & vocabulary"
    if tool.startswith("list_review") or tool.startswith("get_review") or tool.startswith("approve_review") or tool.startswith("reject_review") or "remember" in tool:
        return "Review & governance"
    if "rule" in tool or tool == "run_reasoning" or "derived" in tool or tool == "list_derived_facts":
        return "Reasoning"
    if tool in {"list_processing_jobs", "reset_workspace"}:
        return "Workspace"
    if tool in {"search_chunks", "get_chunk", "entity_facts", "list_typed_facts", "list_mappings", "list_surface_phrases", "list_entity_type_object_labels", "assign_entity_types", "clear_entity_types", "invalidate_entities", "delete_document", "delete_entity", "propose_mapping", "update_mapping_status", "get_statement"}:
        return "Knowledge & ledger"
    if tool in {"paths", "query_graph", "get_graph_summary", "get_graph_analytics", "export_graph", "update_node", "delete_node", "add_entity", "add_relationship", "extract_entities", "extract_relations", "record_decision", "query_decisions", "find_precedents", "get_causal_chain"}:
        return "Graph & decisions"
    return "Other"


def _escape_mdx_text(text: str) -> str:
    """Escape text embedded in MDX (curlies are JSX expressions)."""
    return (
        text.replace("\\", "\\\\")
        .replace("{", "\\{")
        .replace("}", "\\}")
    )


def _escape_md_cell(text: str) -> str:
    return _escape_mdx_text(text).replace("|", "\\|").replace("\n", " ")


def _build_tables() -> str:
    from basis.application.tool_catalog.catalog import OPERATIONS, mcp_exposed
    from basis.application.tool_catalog.mcp_access import mcp_tool_access
    from basis.application.tool_catalog.mcp_metadata import MCP_TOOL_METADATA

    tools = sorted(name for name in OPERATIONS if mcp_exposed(name))
    missing_meta = [t for t in tools if t not in MCP_TOOL_METADATA]
    if missing_meta:
        raise SystemExit(f"MCP_TOOL_METADATA missing keys: {missing_meta}")

    by_cat: dict[str, list[str]] = {}
    for name in tools:
        by_cat.setdefault(_category(name), []).append(name)

    order = [
        "Workspace",
        "Knowledge & ledger",
        "Graph & decisions",
        "Ontology & vocabulary",
        "Reasoning",
        "Review & governance",
        "Connectors",
        "Other",
    ]

    parts: list[str] = []
    for cat in order:
        names = by_cat.get(cat)
        if not names:
            continue
        parts.append(f"### {cat}\n")
        parts.append("| Tool | Access | Description |")
        parts.append("| --- | --- | --- |")
        for name in names:
            desc = MCP_TOOL_METADATA[name]["description"]
            if isinstance(desc, str):
                desc_text = desc
            else:
                desc_text = str(desc)
            access = mcp_tool_access(name)
            parts.append(
                f"| `{name}` | {access} | {_escape_md_cell(desc_text)} |"
            )
        parts.append("")
    return "\n".join(parts)


def _render(locale: str, tables: str) -> str:
    if locale == "en":
        intro = """---
title: "MCP tools index"
sidebarTitle: "MCP tools"
description: "Static workspace MCP tools generated from tool_catalog (names, access class, descriptions)."
---

""" + GENERATED_MARKER + """

Static core tools exposed on workspace MCP `tools/list`. **Connector manifest tools** (`connector_\\{service\\}__…`) are created per provider bundle and are not listed here.

Input schemas: call `tools/list` on a workspace MCP endpoint or use [Swagger](/swagger) / [workspace OpenAPI](/openapi/v1/workspaces.json). See [Agent workflows](/docs/agent-workflows).

"""
    else:
        intro = """---
title: "MCP 工具索引"
sidebarTitle: "MCP 工具"
description: "由 tool_catalog 生成的静态工作区 MCP 工具列表（名称、读写类、英文描述）。"
---

""" + GENERATED_MARKER + """

工作区 MCP `tools/list` 暴露的**静态核心工具**。**连接器 Manifest 工具**（`connector_\\{service\\}__…`）按提供方动态生成，不在此表。

参数 schema：对工作区 MCP 调用 `tools/list`，或使用 [Swagger](/swagger) / [工作区 OpenAPI](/openapi/v1/workspaces.json)。参见 [智能体工作流](/docs/agent-workflows)。

下表描述为服务端元数据（英文）。

"""
    return intro + tables


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if generated files differ (CI drift).",
    )
    args = parser.parse_args()

    tables = _build_tables()
    en_body = _render("en", tables)
    zh_body = _render("zh", tables)

    if args.check:
        for path, expected in ((OUT_EN, en_body), (OUT_ZH, zh_body)):
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                print(f"Drift: {path} (run generate-product-docs-mcp-tools.py)", file=sys.stderr)
                return 1
        print("mcp-tools.mdx OK")
        return 0

    OUT_EN.parent.mkdir(parents=True, exist_ok=True)
    OUT_EN.write_text(en_body, encoding="utf-8")
    OUT_ZH.write_text(zh_body, encoding="utf-8")
    print(f"Wrote {OUT_EN.relative_to(REPO_ROOT)}")
    print(f"Wrote {OUT_ZH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
