#!/usr/bin/env node
/**
 * Regenerate:
 * - modules/<domain>/<seg>/i18n/index.ts (default en/zh barrels)
 * - src/i18n/module-locales.ts (all module namespace imports)
 *
 * Run from web/: npx tsx scripts/refresh-module-i18n-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const srcRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src');
const modulesRoot = path.join(srcRoot, 'modules');

const DOMAINS = ['public', 'admin', 'workspace'];
const moduleEntries = [];

for (const domain of DOMAINS) {
  const domainDir = path.join(modulesRoot, domain);
  if (!fs.existsSync(domainDir)) continue;
  for (const seg of fs.readdirSync(domainDir).sort()) {
    if (seg.startsWith('_')) continue;
    const modRel = `${domain}/${seg}`;
    const i18nRoot = path.join(domainDir, seg, 'i18n');
    const enFile = path.join(i18nRoot, 'en.ts');
    const zhFile = path.join(i18nRoot, 'zh.ts');
    if (!fs.existsSync(enFile) || !fs.existsSync(zhFile)) continue;

    const url = pathToFileURL(enFile).href;
    const modNS = await import(url);
    if (modNS.default == null) {
      console.warn(`skip ${modRel}: en.ts must use export default { … }`);
      continue;
    }
    const rawName = domain === 'admin' ? `admin-${seg}` : seg;
    const namespace = rawName.replace(/-/g, '_');

    const lines = [
      `/** Module i18n namespace \`${namespace}\`. Edit \`en.ts\` and \`zh.ts\` (default export). */`,
      `export { default as en } from './en.js';`,
      `export { default as zh } from './zh.js';`,
      '',
    ];
    fs.writeFileSync(path.join(i18nRoot, 'index.ts'), lines.join('\n'));
    moduleEntries.push({ modRel, rawName, namespace });
    console.log(`updated modules/${modRel}/i18n/index.ts (${namespace})`);
  }
}

moduleEntries.sort((a, b) => a.rawName.localeCompare(b.rawName));

const importLines = moduleEntries.map(
  ({ modRel, namespace }) =>
    `import { en as ${namespace}_en, zh as ${namespace}_zh } from '@/modules/${modRel}/i18n/index.js';`,
);

const enBody = moduleEntries.map(({ namespace }) => `  ${namespace}: ${namespace}_en,`).join('\n');
const zhBody = moduleEntries.map(({ namespace }) => `  ${namespace}: ${namespace}_zh,`).join('\n');
const segments = moduleEntries.map(({ rawName }) => `  '${rawName}',`).join('\n');

const moduleLocales = `/** Aggregated module namespaces — generated by scripts/refresh-module-i18n-index.mjs */

${importLines.join('\n')}

/** Feature module identifiers (hyphenated). */
export const LOCALE_MODULE_SEGMENTS = [
${segments}
] as const;

export const moduleLocalesEn = {
${enBody}
} as const;

export const moduleLocalesZh = {
${zhBody}
} as const;
`;

fs.writeFileSync(path.join(srcRoot, 'i18n', 'module-locales.ts'), moduleLocales);
console.log(`wrote i18n/module-locales.ts (${moduleEntries.length} modules)`);
